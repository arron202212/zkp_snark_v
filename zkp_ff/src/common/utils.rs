#[test]
fn test_random_element_non_zero_one() {
    for _ in 0..100 {
        let x = random_element_non_zero_one::<Fp>();

        assert!(!x.is_zero());
        assert_ne!(x, Fp::one());
    }
}

#[test]
fn test_random_element_exclude() {
    let excluded = Fp::one();

    for _ in 0..100 {
        let x = random_element_exclude(excluded);

        assert_ne!(x, excluded);
    }
}
